/** Plural forms. Romanian puts "de" before the noun from 20 up (20 de ore). */
const PLURAL = {
  en: (n, one, many) => (n === 1 ? one : many),
  el: (n, one, many) => (n === 1 ? one : many),
  ro: (n, one, many) => {
    if (n === 1) return one;
    const r = n % 100;
    return n === 0 || (r >= 1 && r <= 19) ? many : `de ${many}`;
  },
};

